"""Content-addressed storage for original documents (local disk during development).

A file is stored under its own SHA-256 fingerprint:
    storage/originals/ef/eff11f5f...d8.pdf
so identical content is stored exactly once and a stored file can never be silently
replaced by different bytes under the same name. Client-supplied filenames are NEVER used
as paths; they are only kept as metadata.
"""

import hashlib
import shutil
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from app.services.errors import UploadRejected

_BLOCK = 1024 * 1024  # work in 1 MB blocks so large PDFs are never read into memory at once


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(_BLOCK), b""):
            digest.update(block)
    return digest.hexdigest()


def original_key(sha256: str, suffix: str) -> str:
    """Storage key (relative to the storage root). Two-character sub-folders keep any one
    directory small, the same layout Git uses for its objects."""
    return f"originals/{sha256[:2]}/{sha256}{suffix.lower()}"


def resolve(storage_root: Path, key: str) -> Path:
    """Absolute path for a storage key, refusing anything that would escape the storage root
    (defence in depth: keys are generated by us, never taken from a request)."""
    root = storage_root.resolve()
    path = (root / key).resolve()
    if not path.is_relative_to(root):
        raise ValueError(f"storage key escapes the storage root: {key!r}")
    return path


def store_original(storage_root: Path, source: Path, sha256: str) -> str:
    """Copy `source` into storage under its content address. No-op if already stored."""
    key = original_key(sha256, source.suffix)
    target = storage_root / key
    if not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        partial = target.with_name(target.name + ".part")
        shutil.copyfile(source, partial)
        partial.replace(target)  # atomic rename: a half-copied file never has the final name
    return key


@dataclass
class ReceivedFile:
    """An upload written to storage/tmp and fingerprinted, not yet accepted."""

    temp_path: Path
    sha256: str
    size_bytes: int

    def discard(self) -> None:
        self.temp_path.unlink(missing_ok=True)


def receive_upload(stream: BinaryIO, storage_root: Path, max_bytes: int) -> ReceivedFile:
    """Copy an upload into storage/tmp block by block, hashing as we go and stopping as soon
    as it exceeds max_bytes."""
    tmp_dir = storage_root / "tmp"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    temp_path = tmp_dir / f"upload-{uuid.uuid4().hex}.part"
    digest, size = hashlib.sha256(), 0
    try:
        with temp_path.open("wb") as out:
            for block in iter(lambda: stream.read(_BLOCK), b""):
                size += len(block)
                if size > max_bytes:
                    raise UploadRejected("too_large", f"File exceeds the {max_bytes // (1024 * 1024)} MB limit")
                digest.update(block)
                out.write(block)
    except BaseException:
        temp_path.unlink(missing_ok=True)
        raise
    if size == 0:
        temp_path.unlink(missing_ok=True)
        raise UploadRejected("invalid", "The file is empty")
    return ReceivedFile(temp_path, digest.hexdigest(), size)


def accept_upload(storage_root: Path, received: ReceivedFile, suffix: str) -> str:
    """Move a received file to its content address (atomic rename) and return the key."""
    key = original_key(received.sha256, suffix)
    target = storage_root / key
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():  # same bytes already stored (e.g. by the seed): keep one copy
        received.discard()
    else:
        received.temp_path.replace(target)
    return key
